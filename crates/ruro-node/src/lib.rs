/// Result type used throughout the node API.
pub type Result<T = (), E = anyhow::Error> = core::result::Result<T, E>;

/// Behaviour of a node. Only [`Node::step`] is required.
pub trait Node: Send + 'static {
    /// Called once on the node's thread before the first step.
    fn start(&mut self, _ctx: &mut Ctx) -> Result {
        Ok(())
    }

    /// Called whenever the node is triggered: on its timer if it has a rate,
    /// otherwise when any input receives data.
    fn step(&mut self, ctx: &mut Ctx) -> Result;

    /// Called once when the graph stops.
    fn stop(&mut self, _ctx: &mut Ctx) {}

    /// Called once, on the node's thread, when the emergency stop engages.
    ///
    /// Nodes that drive actuators should command a safe state here (zero
    /// velocity, brakes on) and keep doing so while [`Ctx::estopped`] is true.
    /// Other nodes keep running normally, so sensors and logging stay live.
    fn on_estop(&mut self, _ctx: &mut Ctx) {}
}

/// Static metadata and construction for a node type. Generated by `#[derive(Node)]`.
pub trait NodeSpec: Sized {
    fn descriptor() -> NodeDescriptor;
    fn build(b: &mut Builder) -> Result<Self>;
    fn set_param(&mut self, name: &str, value: &serde_json::Value) -> Result;
}

#[doc(hidden)]
pub mod __private {
    pub use inventory;
    pub use serde_json;

    use crate::{Builder, DynNode, Node, NodeSpec, Result};

    pub fn factory<T: Node + NodeSpec>(b: &mut Builder) -> Result<Box<dyn DynNode>> {
        Ok(Box::new(T::build(b)?))
    }
}
