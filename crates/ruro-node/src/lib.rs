//! The node API.
//!
//! A node is a struct whose fields are its ports and parameters. The
//! `#[derive(Node)]` macro (re-exported by the `ruro` crate) generates the
//! [`NodeSpec`] impl and registers the type; the author implements [`Node`].
//!
//! Ports are typed. Within a process a sent message is shared by reference
//! count with every connected input; across processes the host attaches a
//! [`RawSink`] that writes the encoding straight into shared memory.

