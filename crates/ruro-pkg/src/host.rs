//! `ruro build`: generate and compile a host binary that links every package
//! of a `ruro.toml`.
//!
//! The host crate is written to `.ruro/host/` next to the manifest and
//! regenerated on every build. Its `main` calls each package's `link()` and
//! then `ruro_host::main()`. It also answers `<host> schemas` with the JSON
//! schemas of every message type it links, for `ruro schema --host`.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

use crate::manifest::{Manifest, RURO_GIT, lib_name, quote};

/// The ruro crates a host may pull in, for `[patch]` sections.
const RURO_CRATES: &[&str] = &[
    "ruro",
    "ruro-msg",
    "ruro-macros",
    "ruro-node",
    "ruro-graph",
    "ruro-host",
    "ruro-proto",
    "ruro-transport",
    "ruro-nodes-std",
];

/// A generated host crate.
#[derive(Debug, Clone)]
pub struct HostCrate {
    /// Directory holding the crate's `Cargo.toml`.
    pub dir: PathBuf,
    /// Binary name.
    pub name: String,
}

/// Options for [`build`].
#[derive(Debug, Clone, Default)]
pub struct BuildOptions {
    /// Build without optimizations (faster to compile).
    pub debug: bool,
    /// Cargo target directory; defaults to `.ruro/host/target`.
    pub target_dir: Option<PathBuf>,
    /// Lockfile to start from if the host has none yet, e.g. a ruro
    /// checkout's `Cargo.lock`, so dependency versions match it.
    pub seed_lockfile: Option<PathBuf>,
    /// Pass `--offline` to cargo.
    pub offline: bool,
}

/// Renders the host's `Cargo.toml`.
pub fn cargo_toml(manifest: &Manifest, base: &Path) -> String {
    let ruro = manifest.ruro_source().resolved(base);
    let name = manifest.host_name();
    let crate_dep = |krate: &str| {
        let sub = format!("crates/{krate}");
        ruro.dependency(krate, ruro.path.as_ref().map(|_| sub.as_str()))
    };
    let mut out = format!(
        "# Generated by `ruro build` from {}. Do not edit: it is rewritten on every build.\n\
         [package]\n\
         name = {}\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\n\
         [[bin]]\n\
         name = {}\n\
         path = \"src/main.rs\"\n\n\
         [dependencies]\n\
         ruro = {}\n\
         ruro-host = {}\n",
        base.join(crate::MANIFEST).display(),
        quote(&name),
        quote(&name),
        crate_dep("ruro"),
        crate_dep("ruro-host"),
    );
    for (krate, src) in &manifest.packages {
        out.push_str(&format!(
            "{} = {}\n",
            quote(krate),
            src.resolved(base).dependency(krate, None)
        ));
    }
    // Packages that depend on ruro from the git repository must resolve to
    // the same ruro crates as the host, or node registrations end up in a
    // second copy of the registry. Patch the repository to the local tree.
    if let Some(path) = &ruro.path {
        out.push_str(&format!("\n[patch.{}]\n", quote(RURO_GIT)));
        for krate in RURO_CRATES {
            let dir = if krate.starts_with("ruro-nodes-") {
                "nodes"
            } else {
                "crates"
            };
            out.push_str(&format!(
                "{krate} = {{ path = {} }}\n",
                quote(&path.join(dir).join(krate).to_string_lossy())
            ));
        }
    }
    out.push_str(
        "\n[profile.release]\n\
         lto = \"thin\"\n\
         codegen-units = 1\n\
         panic = \"unwind\"\n\
         strip = \"debuginfo\"\n\n\
         # A standalone crate, never part of an enclosing workspace.\n\
         [workspace]\n",
    );
    out
}

/// Renders the host's `src/main.rs`.
pub fn main_rs(manifest: &Manifest) -> String {
    let mut out = String::from(
        "//! Generated by `ruro build`. Do not edit: it is rewritten on every build.\n\n\
         fn main() {\n",
    );
    // Dependencies are keyed by their manifest name, so that is the crate's
    // name in Rust even when `package` renames it.
    for krate in manifest.packages.keys() {
        out.push_str(&format!("    {}::link();\n", lib_name(krate)));
    }
    out.push_str(
        "    if std::env::args().nth(1).as_deref() == Some(\"schemas\") {\n\
         \x20       let schemas: Vec<_> = ruro::msg::schema::registered().into_values().collect();\n\
         \x20       println!(\"{}\", ruro::serde_json::to_string_pretty(&schemas).unwrap());\n\
         \x20       return;\n\
         \x20   }\n\
         \x20   ruro_host::main();\n\
         }\n",
    );
    out
}

/// Writes the host crate for the manifest at `manifest_path`.
pub fn generate(manifest_path: &Path) -> Result<(Manifest, HostCrate)> {
    let manifest = Manifest::load(manifest_path)?;
    if manifest.packages.is_empty() {
        bail!(
            "{} lists no [packages]; add at least one",
            manifest_path.display()
        );
    }
    let base = manifest_path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."))
        .canonicalize()?;
    let dir = base.join(".ruro").join("host");
    std::fs::create_dir_all(dir.join("src"))?;
    std::fs::write(dir.join("Cargo.toml"), cargo_toml(&manifest, &base))?;
    std::fs::write(dir.join("src/main.rs"), main_rs(&manifest))?;
    let name = manifest.host_name();
    Ok((manifest, HostCrate { dir, name }))
}

/// Generates and compiles the host. Returns the path of the binary.
pub fn build(manifest_path: &Path, opts: &BuildOptions) -> Result<PathBuf> {
    let (_, host) = generate(manifest_path)?;
    let lock = host.dir.join("Cargo.lock");
    if let Some(seed) = &opts.seed_lockfile
        && !lock.exists()
    {
        std::fs::copy(seed, &lock).with_context(|| format!("copying {}", seed.display()))?;
    }
    let target_dir = opts
        .target_dir
        .clone()
        .unwrap_or_else(|| host.dir.join("target"));
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let mut cmd = Command::new(cargo);
    cmd.arg("build")
        .arg("--manifest-path")
        .arg(host.dir.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target_dir);
    if !opts.debug {
        cmd.arg("--release");
    }
    if opts.offline {
        cmd.arg("--offline");
    }
    let status = cmd.status().context("running cargo")?;
    if !status.success() {
        bail!("cargo build of the host failed");
    }
    let profile = if opts.debug { "debug" } else { "release" };
    let bin = target_dir.join(profile).join(&host.name);
    if !bin.exists() {
        bail!("cargo succeeded but {} is missing", bin.display());
    }
    Ok(bin)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest() -> Manifest {
        Manifest::parse(
            r#"
[project]
name = "bot"
[ruro]
path = "/src/ruro"
[packages]
my-nodes = { path = "nodes" }
vision = { git = "https://example.com/vision.git", tag = "v1" }
"#,
        )
        .unwrap()
    }

    #[test]
    fn host_cargo_toml_links_packages_and_patches_ruro() {
        let toml_text = cargo_toml(&manifest(), Path::new("/proj"));
        let t: toml::Table = toml::from_str(&toml_text).unwrap();
        assert_eq!(t["package"]["name"].as_str(), Some("bot-host"));
        let deps = t["dependencies"].as_table().unwrap();
        assert_eq!(
            deps["ruro-host"]["path"].as_str(),
            Some("/src/ruro/crates/ruro-host")
        );
        assert_eq!(deps["my-nodes"]["path"].as_str(), Some("/proj/nodes"));
        assert_eq!(deps["vision"]["tag"].as_str(), Some("v1"));
        let patch = t["patch"][RURO_GIT].as_table().unwrap();
        assert_eq!(
            patch["ruro-nodes-std"]["path"].as_str(),
            Some("/src/ruro/nodes/ruro-nodes-std")
        );
        assert!(t.contains_key("workspace"));
    }

    #[test]
    fn host_main_links_every_package() {
        let main = main_rs(&manifest());
        assert!(main.contains("    my_nodes::link();\n    vision::link();\n"));
        assert!(main.contains("ruro_host::main();"));
        syn::parse_file(&main).unwrap();
    }

    #[test]
    fn generate_writes_the_crate() {
        let dir = tempfile::tempdir().unwrap();
        let m = dir.path().join("ruro.toml");
        std::fs::write(&m, "[packages]\na = { path = \".\" }\n").unwrap();
        let (_, host) = generate(&m).unwrap();
        assert!(host.dir.join("Cargo.toml").exists());
        assert!(host.dir.join("src/main.rs").exists());
        assert_eq!(host.name, "ruro-project-host");
        std::fs::write(&m, "").unwrap();
        assert!(generate(&m).is_err(), "no packages");
    }
}
